def boolean_to_string(b):
    """
    Convierte un valor booleano en una cadena de texto

    Parametros:
        b (bool): Valor booleano, True o False

    Devuelve:
        str: El valor booleano convertido a texto
    """

    # Convertimos el valor booleano a una cadena de texto
    # Devolvemos el texto convertido
    return str(b)


# Probamos la funcion con diferentes ejemplos
print("Prueba 1:", boolean_to_string(True))   # Esperado: True
print("Prueba 2:", boolean_to_string(False))  # Esperado: False